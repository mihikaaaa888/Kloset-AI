// Buy/rent price bands per price tier (USD). Rent is priced per week, at
// roughly 8-12% of the buy price, the way real rental marketplaces price
// against retail value.
// Indian retail price points, in rupees.
const PRICE_BAND: Record<CatalogItem['priceRange'], [number, number]> = {
  budget: [999, 2400],
  mid: [2500, 5900],
  premium: [6000, 14500],
  luxury: [15000, 40000],
}

// Small deterministic hash so the same item always gets the same "random"
// price/image pick — stable across renders and reloads.
function hashString(s: string): number {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0
  return h
}

function enrichCatalogItem(item: RawCatalogItem, categoryIndex: number): CatalogItem {
  const pool = CATEGORY_IMAGE_POOL[item.category]
  const itemColours = item.colours.map((c) => c.toLowerCase())

  // Prefer a photo whose visible colour actually overlaps the item's stated
  // colour(s) over blindly cycling the pool — that's what put a black tee
  // under "White Linen Oversized Shirt" and a blue shirt under "Black
  // Ribbed Turtleneck". Among equally-good matches, cycle by category index
  // so items don't all collapse onto the single best-matching photo.
  const scored = pool.map((img) => ({
    img,
    score: img.colours.some((c) => itemColours.includes(c)) ? 1 : 0,
  }))
  const bestScore = Math.max(...scored.map((s) => s.score))
  const candidates = scored.filter((s) => s.score === bestScore)
  const chosen = candidates[categoryIndex % candidates.length].img
  const pick = PRODUCT_PICKS[item.id]
  const imageUrl = pick?.image ?? `https://images.unsplash.com/${chosen.id}?w=600&q=80&auto=format&fit=crop`

  const hash = hashString(item.id)
  const [lo, hi] = PRICE_BAND[item.priceRange]
  // Rounded to a retail-style ₹x,x99 price, and a weekly rental of ~8–12% (min ₹299).
  const estimatedPrice = Math.round((lo + (hash % 100) / 100 * (hi - lo)) / 100) * 100 - 1
  const rentPricePerWeek = Math.max(299, Math.round((estimatedPrice * (0.08 + (hash % 40) / 1000)) / 50) * 50 - 1)

  const query = encodeURIComponent(`${item.name} ${item.material}`)
  const shopUrl = pick?.url ?? `https://www.google.com/search?tbm=shop&q=${query}`
  const rentUrl = `https://www.google.com/search?q=${encodeURIComponent(`rent ${item.name}`)}`

  return { ...item, gender: item.gender ?? 'women', brand: pick?.brand, imageUrl, estimatedPrice, rentPricePerWeek, shopUrl, rentUrl }
}

const categoryCounters: Partial<Record<ClothingCategory, number>> = {}

export const ALL_CATALOG_ITEMS: CatalogItem[] = RAW_CATALOG_ITEMS.map((item) => {
  const idx = categoryCounters[item.category] ?? 0
  categoryCounters[item.category] = idx + 1
  return enrichCatalogItem(item, idx)
})

